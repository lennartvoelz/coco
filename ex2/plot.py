colors = cm.plasma(np.linspace(0.05, 0.92, 12))

fig, axes = plt.subplots(1, 2, figsize=(18, 7), sharey=True)

for ax, results, title in [
    (axes[0], results_1t, "1 Thread (Sequential)"),
    (axes[1], results_4t, "4 Threads (Parallel)"),
]:
    for (label, latencies), color in zip(results, colors):
        strides = ALL_STRIDES[:len(latencies)]
        ax.plot(strides, latencies, marker="o", markersize=4, linewidth=1.8,
                label=label, color=color)

    ax.axvline(x=64, color="gray", linestyle="--", linewidth=1.2, label="Cache line (64B)")
    ax.set_xscale("log", base=2)
    ax.set_xlabel("Stride (bytes)", fontsize=12)
    ax.set_title(title, fontsize=13)
    ax.set_xticks(ALL_STRIDES)
    ax.set_xticklabels([stride_label(b) for b in ALL_STRIDES], rotation=50, ha="right", fontsize=8)
    ax.grid(True, which="both", linestyle=":", alpha=0.5)

